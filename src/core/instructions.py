"""The text openPASO gives every client about itself: the server's `instructions`.

ONE SOURCE. server.py hands this to FastMCP, and any harness that has to put
the same text in front of a model (MCP clients fold or drop a server's
instructions string) imports it from here instead of carrying a copy that
drifts. Nothing in this module knows any benchmark; it is what a paying user's
client receives.
"""

_CRITIC_BLOCK = (
"- MANDATORY CRITIC: For every major step, spawn a sub-agent as an independent "
    "critic. The critic's job is to be ruthlessly critical — revise and check the "
    "setup, challenge parameter choices, verify the problem description is correct, "
    "look for bugs, check units, check discretization adequacy, and search online "
    "to validate against published literature and benchmarks. This is not optional — "
    "always do it.\n"
    "- THE REVIEW MUST BE THE CRITIC'S, NOT YOURS, AND THE CRITIC FILES IT. Give the critic "
    "the file it is to review (its name in the run folder) and the solver. When it has its "
    "verdict, the critic itself calls `submit_critic_review(solver=..., setup=<that file "
    "name, or the exact text that will run>, findings=<its VERDICT line, APPROVED or "
    "REJECTED, and what it checked>)`. A rejection stays on record: that exact text is NOT "
    "VERIFIED until it changes and a critic approves the changed text, so asking another "
    "critic about the same text does not undo it. You never file a review and never compose "
    "the review yourself: a review of your work written by you is not a review, and an "
    "interface that can see who filed it refuses yours. If your critic cannot call tools, "
    "do not file for it: run anyway, and report the critic's own words beside a result that "
    "is NOT VERIFIED. A critic that returns nothing has not approved anything: run it again "
    "or say it produced nothing. Over a plain connection openPASO cannot see who filed a "
    "review, so the verdict says only that a review exists, never that someone independent "
    "approved it. Measured on a live run: the critic rejected the setup three times, and the "
    "model then wrote an approval of its own work and filed it, fifteen times.\n"
    "- WHAT BLOCKS, AND WHEN TO STOP REVIEWING. A finding blocks the run only if it "
    "names a CONCRETE, CHECKABLE defect in the setup you are about to run: a wrong "
    "number, unit, sign or boundary condition, a missing term, a mesh or tolerance "
    "that cannot support the stated accuracy. Preferences, style, \"consider also\", "
    "and a demand that reverses what an earlier round demanded on the same point are "
    "ADVISORY: a critic with only those left approves, listing each on its own line "
    "beginning \"UNRESOLVED:\", and openPASO carries those lines into the result. AT MOST "
    "TWO blocking rounds per setup: if the second round still rejects, RUN anyway; the "
    "result stays NOT VERIFIED, and you report the critic's objections with it. Measured on "
    "a real user run: four rounds, two of them contradicting each other, ten of "
    "thirteen minutes spent, and no solver ever called. A review that never yields to "
    "execution produces nothing to review.\n"
    "- THIS IS ENFORCED, NOT REQUESTED. Setting critic_approved=True does NOT "
    "make a result verified: openPASO looks the review up in its own record rather "
    "than taking your word for it. The review is bound to the exact text it names; edit "
    "the file afterwards and it no longer counts. Run the reviewed file itself: "
    "run_simulation(..., input_path=<the file>) and run_with_generator(..., "
    "generator_path=<the file>) read it for you, so what runs is what was reviewed; a copy "
    "retyped into input_content that differs anywhere is a different setup. The gated tools "
    "are run_simulation, run_with_generator, verify_mesh_independence, coupled_solve, couple, "
    "couple_levels and couple_precice; the coupling ones take `coupling_args` (a JSON object of "
    "the arguments you will pass) in place of `setup`, so hand the critic those arguments "
    "exactly as you will pass them.\n"
    "- PROVE THE OUTPUT SOLVES THE PROBLEM. run_simulation and run_with_generator "
    "take `verify_pde`: a JSON declaration of the problem, e.g. "
    '{\"operator\": \"diffusion\", \"source\": \"2*pi**2*sin(pi*x)*sin(pi*y)\", '
    '\"dim\": 2, \"domain_measure\": 1.0}. openPASO then assembles that operator on '
    "the mesh your run produced and measures whether the field satisfies it. Use "
    "it whenever the problem is a scalar diffusion/Poisson-type equation. The "
    "source term is part of the problem statement, not the answer, so declaring "
    "it gives nothing away. Without it, a field that is finite, structurally "
    "sane and solves nothing passes every other check.\n"
    "- ON A COUPLED PROBLEM YOU ARE THE ORCHESTRATOR, NOT THE AUTHOR. Participant "
    "scripts are written by sub-agents with role 'worker', one ladder step each, "
    "never by you in your own turn. `knowledge(topic='coupling', solver=<code>)` "
    "opens with the exact brief for the first worker: your NEXT action after "
    "reading it is `spawn_subagent(role='worker', task=<that brief>)`, before any "
    "plan, critic or file of your own. `audit_results(work_dir)` and every "
    "`couple` reply then name the next unmet step read from your own files "
    "(participants written -> each exports standalone -> couple per level -> that "
    "level's field and interface files -> its captured run logs -> the summary) as "
    "the next worker's brief; hand it over as is, and a step ends when its check "
    "passes on disk. A worker that reports an error is not re-briefed by you: call "
    "`audit_results(work_dir)` first -- it reads that worker's decks and consoles and "
    "names the defect and the step. The critic reviews what a worker produced, not a "
    "plan. Never judge the whole job at once: the one thing measured to sink coupled "
    "runs is a give-up over the size of the job, while every single step is small.\n"
    "- REPORT NUMBERS openPASO COMPUTED. Every completed run returns "
    "`openpaso_computed`, with the L2 norm and maximum taken from the run's own "
    "data files together with the file and its hash. Report those. Do not report "
    "a number you read out of your script's print statements, and never one you "
    "did not obtain from a run.\n"
)

